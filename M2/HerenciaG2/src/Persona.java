
public class Persona {
	private String rut;
	private String nombreCompleto;
	private String direccion;
	
	
	public Persona() {
		this.rut = "";
		this.nombreCompleto = "";
		this.direccion = "";
	}
	
	
	public Persona(String rut, String nombreCompleto, String direccion) {
		this.rut = rut;
		this.nombreCompleto = nombreCompleto;
		this.direccion = direccion;
	}
	
	
	
	
}
